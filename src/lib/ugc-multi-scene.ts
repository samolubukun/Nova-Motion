/**
 * UGC Multi-Scene pipeline — an Arcads/MakeUGC-style upgrade over the single
 * clip UGC mode:
 *
 *   script ─► LLM scene breakdown (hook/product/CTA beats)
 *             └─► per scene: TTS voiceover (one voice) ─► I2V/T2V clip
 *                                        └─► lip-sync mouth to TTS (optional)
 *   ──► timeline of clips + continuous voiceover (played by WavespeedVideo)
 *
 * - The LLM splits the script into 2-6 scenes, each with:
 *   - `lines`    : the spoken words (fed to TTS),
 *   - `visual`   : an image/video-generation prompt describing the character
 *                  in that setting/action (fed to the model),
 *   - `durationSec`: a suggested clip length (used only when TTS is unavailable).
 * - One voiceover is generated for the whole ad (ElevenLabs preferred,
 *   Deepgram fallback) so the voice stays identical across every cut.
 * - Each scene's video is generated by the selected UGC model (I2V when a
 *   reference image is supplied, T2V otherwise) and muted in the composition;
 *   the TTS audio is overlaid on top — exactly how the WavespeedVideo
 *   composition plays TextToVideo/MicroDrama timelines.
 *
 * All AI calls go through the shared WaveSpeed key:
 *   - LLM (OpenAI-compatible): https://llm.wavespeed.ai/v1
 *   - Video:                   https://api.wavespeed.ai/api/v3/{model}
 */

